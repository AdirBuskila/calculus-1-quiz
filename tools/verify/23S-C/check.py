# sympy check of every official answer in 23S-C. Run: PYTHONUTF8=1 py tools/verify/23S-C/check.py
import sympy as sp, mpmath as mp
x,t,y,L,a,b=sp.symbols('x t y L a b',real=True)
r=[]
def ok(name,cond): r.append((name,bool(cond)))
f=2*x*sp.exp(-x**2/2)
ok("Q1 f odd",sp.simplify(f.subs(x,-x)+f)==0)
ok("Q1 f'",sp.simplify(sp.diff(f,x)-2*sp.exp(-x**2/2)*(1-x**2))==0)
ok("Q1 extrema",sp.solve(sp.diff(f,x),x)==[-1,1] and sp.simplify(f.subs(x,1)-2/sp.sqrt(sp.E))==0 and sp.simplify(f.subs(x,-1)+2/sp.sqrt(sp.E))==0)
ok("Q1 f''",sp.simplify(sp.diff(f,x,2)-(-2*x*sp.exp(-x**2/2)*(3-x**2)))==0)
ok("Q1 inflection x=0,+-sqrt3",set(sp.solve(sp.diff(f,x,2),x))=={0,sp.sqrt(3),-sp.sqrt(3)})
ok("Q1 sign table f''",[sp.sign(sp.diff(f,x,2).subs(x,v)) for v in (-3,-1,1,3)]==[-1,1,-1,1])
ok("Q1 asym y=0 both sides",sp.limit(f,x,sp.oo)==0 and sp.limit(f,x,-sp.oo)==0)
seq=[sp.Integer(1)]
for i in range(30): seq.append(seq[-1]/2+1)
ok("Q2a 1<=a_n<2 increasing, a2..a4 = 1.5,1.75,1.875",all(1<=seq[i]<2 and seq[i+1]>seq[i] for i in range(30)) and seq[1:4]==[sp.Rational(3,2),sp.Rational(7,4),sp.Rational(15,8)])
ok("Q2a L=2",sp.solve(sp.Eq(L,L/2+1),L)==[2])
ok("Q2b",sp.simplify(sp.diff(x**2/2-sp.Rational(3,2)*sp.log(x**2+1),x)-(x**3-2*x)/(x**2+1))==0)
sol=sp.solve([a+b-1,2*a+b-3],[a,b]); ok("Q3a a=2,b=-1",sol=={a:2,b:-1})
ok("Q3a f'(1-)=f'(1+)",(2*a+1).subs(sol)==(4-b).subs(sol))
p=2*x**3-x**2+x+1; ok("Q3b f'>0 (disc<0)",sp.Poly(6*x**2-2*x+1,x).discriminant()<0 and p.subs(x,0)==1)
ok("Q3b f(-3)=-65 (official prints -59: arithmetic typo, sign conclusion unaffected)",p.subs(x,-3)==-65)
ok("Q3b f(-3)<0",p.subs(x,-3)<0)
ok("Q4a",sp.limit(((x**2+5*x+4)/(x**2-3*x+7))**(2*x),x,sp.oo)==sp.exp(16))
V=sp.pi*sp.integrate(sp.log(x)**2,(x,1,sp.E)); ok("Q4b volume = pi*(e-2)",sp.simplify(V-sp.pi*(sp.E-2))==0)
ok("Q4b official 0.714 vs e-2=0.718 and missing pi: official DISAGREES (V=pi*(e-2)=2.256)",abs(float(V)-2.2556)<1e-3 and abs(float(sp.E-2)-0.714)>1e-3)
F=y-sp.pi*x*sp.sin(y/2)
dydx=-sp.diff(F,x)/sp.diff(F,y); ok("Q5a F(1,pi)=0",F.subs({x:1,y:sp.pi})==0)
ok("Q5a y'(1)=pi",sp.simplify(dydx.subs({x:1,y:sp.pi}))==sp.pi)
ok("Q5b",sp.limit(sp.log(x)/sp.log(sp.exp(x)-1),x,0,'+')==1)
g=2*x+3*sp.cbrt(x**2)
vals={v:sp.N(2*v+3*sp.Abs(v)**sp.Rational(2,3)) for v in (-2,-1,0)}
ok("Q6a",abs(vals[-1]-1)<1e-12 and vals[0]==0 and abs(vals[-2]-0.7622)<1e-3 and max(vals.values())==vals[-1] and min(vals.values())==0)
ok("Q6b taylor",sp.diff(x**sp.Rational(1,3),x).subs(x,8)==sp.Rational(1,12) and sp.Rational(1,9)/sp.Integer(8)**sp.Rational(5,3)==sp.Rational(1,288))
ok("Q6b 9^(1/3)~2+1/12 within .01",abs(float(sp.cbrt(9))-(2+1/12))<0.01)
for k,v in r: print(k,"OK" if v else "MISMATCH")
print("ALL OK" if all(v for _,v in r) else "FAIL (see MISMATCH lines)")
