"""Source + machine check for the guided course "investigation" (calculus-1, topic function_investigation).

Every option of every question is written next to a sympy expression for its truth value; importing this
module evaluates all of them and asserts that exactly one option of each mcq is true. check.py then
emits courses/investigation/C0N.js from LEVELS and re-reads the emitted files to confirm they match.
"""
import sympy as sp

x = sp.Symbol('x', real=True)
