oo = sp.oo
E = sp.E
R = sp.Rational
exp, log, sqrt = sp.exp, sp.log, sp.sqrt
LEVELS = []
FACTS = []          # (description, bool) for numbers that appear in lessons / explanations
_pos = [0]


def fact(desc, cond):
    assert bool(cond), "FACT FAILED: " + desc
    FACTS.append(desc)


def eq(a, b):
    return sp.simplify(a - b) == 0


def sgn(expr, a, b):
    """Sign of a continuous expression on the open interval (a,b): verified zero-free, sign at an interior point."""
    I = sp.Interval.open(a, b)
    assert sp.solveset(expr, x, I) == sp.EmptySet, ("zero inside", expr, a, b)
    if a == -oo and b == oo:
        m = 0
    elif a == -oo:
        m = b - 1
    elif b == oo:
        m = a + 1
    else:
        m = (a + b) / 2
    v = sp.N(expr.subs(x, m))
    assert v != 0
    return 1 if v > 0 else -1


def lim(f, pt, d=None):
    return sp.limit(f, x, pt, d) if d else sp.limit(f, x, pt)


def mcq(qid, question, opts, explanation, recap):
    """opts: list of (text, truth). Exactly one truth is True; it is moved to a rotating position."""
    truths = [bool(t) for _, t in opts]
    assert sum(truths) == 1, (qid, truths)
    assert len({t for t, _ in opts}) == len(opts), qid
    k = _pos[0]
    _pos[0] += 1
    ci = truths.index(True)
    items = [o for o in opts]
    correct = items.pop(ci)
    at = [2, 0, 3, 1][k % 4] % len(opts)
    items.insert(at, correct)
    options = [{"id": "abcdefgh"[i], "value": t} for i, (t, _) in enumerate(items)]
    return {"id": qid, "question": question, "options": options, "correctId": "abcdefgh"[at],
            "explanation": explanation, "recap": recap}


def numeric(qid, prompt, answer, truth, explain, recap, tol=0):
    assert abs(float(truth) - float(answer)) <= max(tol, 1e-9) * (1 if tol else 1) + (0.5e-4 if tol else 0), (qid, answer, truth)
    return {"id": qid, "step": {"type": "numeric", "prompt": prompt, "answer": answer, "tol": tol, "explain": explain},
            "recap": recap}


def level(lid, order, icon, title, goal, lesson, questions, boss=False):
    LEVELS.append({"id": lid, "order": order, "icon": icon, "title": title, "goal": goal, "boss": boss,
                   "lesson": lesson, "questions": questions})


