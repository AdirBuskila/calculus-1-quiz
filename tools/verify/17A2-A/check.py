import sympy as sp
x = sp.symbols('x', real=True)
p = sp.symbols('p', positive=True)
a, b = sp.symbols('a b')
r = []
f = (x - 1) * sp.exp(x)
r.append(("Q1 f'", sp.simplify(sp.diff(f, x) - x * sp.exp(x)) == 0))
r.append(("Q1 f''", sp.simplify(sp.diff(f, x, 2) - (x + 1) * sp.exp(x)) == 0))
r.append(("Q1 y(0), y(-1)", f.subs(x, 0) == -1 and sp.simplify(f.subs(x, -1) + 2 / sp.E) == 0))
r.append(("Q1 limits", sp.limit(f, x, -sp.oo) == 0 and sp.limit(f / x, x, sp.oo) == sp.oo))
a2 = sp.Rational(1, 2) * (5 + sp.Rational(4, 5))
r.append(("Q2 a2=2.9", a2 == sp.Rational(29, 10)))
L = sp.symbols('L', positive=True)
r.append(("Q2 L=2", sp.solve(sp.Eq(L, (L + 4 / L) / 2), L) == [2]))
r.append(("Q3a", sp.limit(p * sp.log((p + 1) / (p - 1)), p, sp.oo) == 2))
r.append(("Q3b", sp.integrate(sp.pi * ((5 - p)**2 - 16 / p**2), (p, 1, 4)) == 9 * sp.pi))
r.append(("Q3b intersections", sorted(sp.solve(p * (5 - p) - 4, p)) == [1, 4]))
r.append(("Q4a", sp.solve(sp.Eq(-1 / p**2, -p), p) == [1]))
y = p**4 / 8 + 1 / (4 * p**2)
r.append(("Q4b 1+y'^2", sp.simplify(1 + sp.diff(y, p)**2 - (p**6 + 1)**2 / (4 * p**6)) == 0))
r.append(("Q4b", sp.integrate(sp.diff(y, p) + 1 / (1) * 0 + p**3 / 2 + 1 / (2 * p**3) - sp.diff(y, p), (p, 1, 4)) == sp.Rational(2055, 64)))
aa, bb = sp.symbols('aa bb')
r.append(("Q5a", sp.simplify((2 * bb**2 + 5 * bb - 2 * aa**2 - 5 * aa) / (bb - aa) - (2 * bb + 2 * aa + 5)) == 0))
r.append(("Q5b", sp.simplify(sp.diff(-sp.exp(-x**2) * (x**2 + 1) / 2, x) - x**3 * sp.exp(-x**2)) == 0))
r.append(("Q6a right limit 2/a", sp.limit(2 * x / sp.asin(a * x), x, 0, '+') == 2 / a))
a0 = sp.Rational(1, 2)
fl = (sp.exp(a * x) - a**(-a * x)) / sp.log(1 + b * x)
lm = sp.limit(fl.subs(a, a0).subs(b, (1 + sp.log(a0)) / 8), x, 0, '-')
r.append(("Q6a left limit = 4 at a=1/2, b=(1+ln0.5)/8", sp.simplify(lm - 4) == 0))
lm2 = sp.limit(fl.subs({a: sp.Rational(3, 2), b: 2}), x, 0, '-')
r.append(("Q6a general left limit a(1+ln a)/b", sp.simplify(lm2 - sp.Rational(3, 2) * (1 + sp.log(sp.Rational(3, 2))) / 2) == 0))
r.append(("Q6b", sp.simplify(sp.diff(sp.log((p - 1) / (p + 1)) / 4 - sp.atan(p) / 2, p) - 1 / (p**4 - 1)) == 0))
r.append(("Q6b A B C D", sp.simplify(sp.Rational(1, 4) * (p + 1) * (p**2 + 1) - sp.Rational(1, 4) * (p - 1) * (p**2 + 1)
                                       - sp.Rational(1, 2) * (p**2 - 1) - 1) == 0))
for k, v in r:
    print(("OK   " if v else "FAIL ") + k)
