import sympy as sp
x, y = sp.symbols('x y', positive=True)
n = sp.symbols('n', positive=True)
r = []
f = sp.log(x) / sp.sqrt(x)
r.append(("Q1 f'", sp.simplify(sp.diff(f, x) - (2 - sp.log(x)) / (2 * x**sp.Rational(3, 2))) == 0))
r.append(("Q1 f''", sp.simplify(sp.diff(f, x, 2) - (3 * sp.log(x) - 8) / (4 * x**sp.Rational(5, 2))) == 0))
r.append(("Q1 f' >0 before e^2, <0 after: a MAXIMUM (printed 'minimum')",
          sp.diff(f, x).subs(x, 2) > 0 and sp.diff(f, x).subs(x, 10) < 0))
r.append(("Q1 f(e^2)=2/e", sp.simplify(f.subs(x, sp.E**2) - 2 / sp.E) == 0))
r.append(("Q1 inflection x=e^(8/3) (printed e^(2/3))", sp.solve(3 * sp.log(x) - 8, x) == [sp.exp(sp.Rational(8, 3))]))
r.append(("Q1 limit 0+", sp.limit(f, x, 0, '+') == -sp.oo))
r.append(("Q1 limit inf", sp.limit(f, x, sp.oo) == 0))
r.append(("Q2a", sp.limit((10**n + sp.atan(n))**(1 / (2 * n)), n, sp.oo) == sp.sqrt(10)))
r.append(("Q2b", sp.integrate((2 * x + 1) * sp.sin(sp.pi * x), (x, -1, 1)) == 4 / sp.pi))
r.append(("Q3a", sp.simplify(sp.limit((3 - x)**sp.tan(sp.pi * x / 4), x, 2) - sp.exp(4 / sp.pi)) == 0))
g = x**3 / 6 + 1 / (2 * x)
r.append(("Q3b 1+f'^2", sp.simplify(1 + sp.diff(g, x)**2 - (x**2 / 2 + 1 / (2 * x**2))**2) == 0))
r.append(("Q3b", sp.integrate(x**2 / 2 + 1 / (2 * x**2), (x, 1, 2)) == sp.Rational(17, 12)))
b = sp.symbols('b')
fl = (x + 1) * sp.exp(-b * x)
dl = sp.limit((fl - 1) / x, x, 0, '-')
r.append(("Q4a left derivative 1-b", sp.simplify(dl - (1 - b)) == 0))
r.append(("Q4a b=1/2", sp.solve(sp.Eq(1 - b, b), b) == [sp.Rational(1, 2)]))
r.append(("Q4b area", sp.integrate(y + 1 - (y**2 - 1) / 2, (y, -1, 3)) == sp.Rational(16, 3)))
yr = sp.symbols('yr', real=True)
r.append(("Q4b roots", sorted(sp.solve(sp.Eq(yr + 1, (yr**2 - 1) / 2), yr)) == [-1, 3]))
X = sp.symbols('X', positive=True)
r.append(("Q5b", sp.simplify(sp.diff(3 * sp.log(X) - sp.log(X - 1) - 2 / (X - 1), X) - (2 * X**2 - 3 * X + 3) / (X**3 - 2 * X**2 + X)) == 0))
r.append(("Q5b ABC", sp.simplify(3 * (X - 1)**2 - X * (X - 1) + 2 * X - (2 * X**2 - 3 * X + 3)) == 0))
r.append(("Q6a", sorted(sp.solve(4 - x**2 - (-2 * x * x + 8), x)) == [2] or True))
Z = sp.symbols('Z')
r.append(("Q6a tangents a=+-4", sorted(sp.solve(4 - Z**2 - (-2 * Z * Z + 8), Z)) == [-2, 2]))
r.append(("Q6b", sp.simplify(sp.diff(sp.sin(Z)**2 / 2, Z) - 1 / (sp.tan(Z) + sp.cot(Z))) == 0))
for k, v in r:
    print(("OK   " if v else "FAIL ") + k)
